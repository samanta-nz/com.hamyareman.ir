package com.hamyareman.ir.ui.home

import com.hamyareman.ir.platform.core.common.JalaliDate

/**
 * تعطیلات رسمی ایران — فقط مناسبت‌های ثابت شمسی + چند مناسبت قمریِ سال جاری که تاریخ شمسی‌شان مشخص است.
 * جمعه به‌تنهایی مناسبت نیست.
 */
internal object IranOfficialHolidays {

    fun occasion(j: JalaliDate.Jalali): String? {
        solar[j.month to j.day]?.let { return it }
        lunarOn(j)?.let { return it }
        return null
    }

    /** فقط مناسبت قمریِ همان روز شمسی (برای جابه‌جایی ±۲ روز). */
    fun lunarOn(j: JalaliDate.Jalali): String? = yearly["${j.year}-${j.month}-${j.day}"]

    private val solar = mapOf(
        (1 to 1) to "عید نوروز",
        (1 to 2) to "عید نوروز",
        (1 to 3) to "عید نوروز",
        (1 to 4) to "عید نوروز",
        (1 to 12) to "روز جمهوری اسلامی",
        (1 to 13) to "روز طبیعت",
        (3 to 14) to "رحلت امام خمینی",
        (3 to 15) to "قیام ۱۵ خرداد",
        (11 to 22) to "پیروزی انقلاب اسلامی",
        (12 to 29) to "ملی شدن صنعت نفت",
    )

    /** مناسبت‌های قمری با تاریخ شمسی همان سال (۱۴۰۴–۱۴۰۶). */
    private val yearly = mapOf(
        "1404-1-13" to "عید سعید فطر",
        "1404-1-14" to "تعطیلی عید فطر",
        "1404-3-24" to "عید سعید قربان",
        "1404-4-1" to "عید سعید غدیر خم",
        "1404-4-23" to "تاسوعای حسینی",
        "1404-4-24" to "عاشورای حسینی",
        "1404-6-2" to "اربعین حسینی",
        "1404-6-10" to "رحلت رسول اکرم و شهادت امام حسن",
        "1404-6-12" to "شهادت امام رضا",
        "1404-10-13" to "ولادت حضرت رسول و امام جعفر صادق",
        "1405-1-2" to "عید سعید فطر",
        "1405-1-3" to "تعطیلی عید فطر",
        "1405-3-13" to "عید سعید قربان",
        "1405-3-21" to "عید سعید غدیر خم",
        "1405-4-12" to "تاسوعای حسینی",
        "1405-4-13" to "عاشورای حسینی",
        "1405-5-22" to "اربعین حسینی",
        "1405-5-30" to "رحلت رسول اکرم و شهادت امام حسن",
        "1405-6-1" to "شهادت امام رضا",
        "1405-10-2" to "ولادت حضرت رسول و امام جعفر صادق",
    )
}
